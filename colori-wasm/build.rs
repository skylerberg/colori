use colori_core::cards::*;
use colori_core::colors::SECONDARIES;
use colori_core::types::*;
use std::fmt::Write as FmtWrite;
use std::io::Write;

fn format_ability(ability: &Ability) -> String {
    match ability {
        Ability::Workshop { count } => format!("{{ type: 'workshop', count: {} }}", count),
        Ability::MixColors { count } => format!("{{ type: 'mixColors', count: {} }}", count),
        Ability::LiftCard => "{ type: 'liftCard' }".to_string(),
        Ability::Sell => "{ type: 'sell' }".to_string(),
        Ability::GainGoldCoins { count } => format!("{{ type: 'gainGoldCoins', count: {} }}", count),
        Ability::GainSecondary => "{ type: 'gainSecondary' }".to_string(),
        Ability::GainBowls { count } => format!("{{ type: 'gainBowls', count: {} }}", count),
        Ability::GainBoats { count } => format!("{{ type: 'gainBoats', count: {} }}", count),
    }
}

fn format_abilities(abilities: &[Ability]) -> String {
    let formatted: Vec<String> = abilities.iter().map(format_ability).collect();
    format!("[{}]", formatted.join(", "))
}

fn format_color(color: &Color) -> &'static str {
    match color {
        Color::Red => "Red",
        Color::Vermilion => "Vermilion",
        Color::Orange => "Orange",
        Color::Amber => "Amber",
        Color::Yellow => "Yellow",
        Color::Chartreuse => "Chartreuse",
        Color::Green => "Green",
        Color::Teal => "Teal",
        Color::Blue => "Blue",
        Color::Ultramarine => "Ultramarine",
        Color::Purple => "Purple",
        Color::Fuchsia => "Fuchsia",
    }
}

fn format_material_type(mt: &MaterialType) -> &'static str {
    match mt {
        MaterialType::Textiles => "Textiles",
        MaterialType::Ceramics => "Ceramics",
        MaterialType::Paintings => "Paintings",
    }
}

fn card_variant_name(card: &Card) -> String {
    serde_json::to_value(card)
        .unwrap()
        .as_str()
        .unwrap()
        .to_string()
}

fn buyer_variant_name(buyer: &Buyer) -> String {
    serde_json::to_value(buyer)
        .unwrap()
        .as_str()
        .unwrap()
        .to_string()
}

fn write_pigment_card(out: &mut String, card: &Card) {
    let name = card.name();
    let colors = card.colors();
    let colors_str: Vec<String> = colors.iter().map(|c| format!("'{}'", format_color(c))).collect();
    write!(
        out,
        "  {{\n    kind: 'pigment',\n    name: '{}',\n    colors: [{}],\n    topActions: {},\n  }},\n",
        name.replace('\'', "\\'"),
        colors_str.join(", "),
        format_abilities(card.top_actions()),
    )
    .unwrap();
}

fn write_starter_pigment_card(out: &mut String, card: &Card) {
    let name = card.name();
    let color = card.colors()[0];
    write!(
        out,
        "  {{\n    kind: 'starterPigment',\n    name: '{}',\n    color: '{}',\n    topActions: {},\n  }},\n",
        name,
        format_color(&color),
        format_abilities(card.top_actions()),
    )
    .unwrap();
}

fn write_material_card(out: &mut String, card: &Card) {
    let name = card.name();
    let material_types = card.material_types();
    let colors = card.colors();

    let mt_str: Vec<String> = material_types
        .iter()
        .map(|mt| format!("'{}'", format_material_type(mt)))
        .collect();

    write!(out, "  {{\n    kind: 'material',\n    name: '{}',\n    materialTypes: [{}],\n", name.replace('\'', "\\'"), mt_str.join(", ")).unwrap();
    if !colors.is_empty() {
        write!(out, "    color: '{}',\n", format_color(&colors[0])).unwrap();
        if colors.len() > 1 {
            write!(out, "    colorCount: {},\n", colors.len()).unwrap();
        }
    }
    write!(out, "    topActions: {},\n  }},\n", format_abilities(card.top_actions())).unwrap();
}

fn write_action_card(out: &mut String, card: &Card) {
    let name = card.name();

    write!(
        out,
        "  {{\n    kind: 'special',\n    name: '{}',\n    topActions: {},\n    workshopAbilities: {},\n  }},\n",
        name,
        format_abilities(card.top_actions()),
        format_abilities(card.workshop_abilities()),
    )
    .unwrap();
}

fn main() {
    println!("cargo:rerun-if-changed=../colori-core/src/types.rs");
    println!("cargo:rerun-if-changed=../colori-core/src/cards.rs");
    println!("cargo:rerun-if-changed=../colori-core/src/colors.rs");
    println!("cargo:rerun-if-changed=build.rs");

    let mut out = String::new();

    // Header
    out.push_str("// AUTO-GENERATED by colori-wasm/build.rs — do not edit by hand\n");
    out.push_str("import type { Card, Buyer, Color, AnyCardData, PigmentCardData, StarterPigmentCardData, MaterialCardData, SpecialCardData, BuyerData } from './types';\n\n");

    // PIGMENT_CARDS
    out.push_str("export const PIGMENT_CARDS: PigmentCardData[] = [\n");
    for card in draft_pigment_cards() {
        write_pigment_card(&mut out, &card);
    }
    out.push_str("];\n\n");

    // MATERIAL_CARDS (starter materials)
    out.push_str("export const MATERIAL_CARDS: MaterialCardData[] = [\n");
    for card in starter_material_cards() {
        write_material_card(&mut out, &card);
    }
    out.push_str("];\n\n");

    // DRAFT_MATERIAL_CARDS
    out.push_str("export const DRAFT_MATERIAL_CARDS: MaterialCardData[] = [\n");
    for card in draft_material_cards() {
        write_material_card(&mut out, &card);
    }
    out.push_str("];\n\n");

    // BASIC_PIGMENT_CARDS
    out.push_str("export const STARTER_PIGMENT_CARDS: StarterPigmentCardData[] = [\n");
    for card in starter_pigment_cards() {
        write_starter_pigment_card(&mut out, &card);
    }
    out.push_str("];\n\n");

    // ACTION_CARDS
    out.push_str("export const SPECIAL_CARDS: SpecialCardData[] = [\n");
    for card in action_cards() {
        write_action_card(&mut out, &card);
    }
    out.push_str("];\n\n");

    let secondaries: Vec<String> =
        SECONDARIES.iter().map(|c| format!("'{}'", format_color(c))).collect();
    write!(out, "export const SECONDARIES: Color[] = [{}];\n\n", secondaries.join(", ")).unwrap();

    write!(out, "export const STARTER_DECK_SIZE = {};\n\n", starter_deck().len()).unwrap();

    // CHALK_CARD
    let chalk = chalk_card();
    out.push_str("export const CHALK_CARD: SpecialCardData = {\n");
    write!(
        out,
        "  kind: 'special',\n  name: '{}',\n  topActions: {},\n  workshopAbilities: {},\n",
        chalk.name(),
        format_abilities(chalk.top_actions()),
        format_abilities(chalk.workshop_abilities()),
    )
    .unwrap();
    out.push_str("};\n\n");

    // PRIMARIES_CARD: an ordinary pigment card carrying one of each primary.
    let primaries = primaries_card();
    let primaries_colors: Vec<String> =
        primaries.colors().iter().map(|c| format!("'{}'", format_color(c))).collect();
    out.push_str("export const PRIMARIES_CARD: PigmentCardData = {\n");
    write!(
        out,
        "  kind: 'pigment',\n  name: '{}',\n  colors: [{}],\n  topActions: {},\n",
        primaries.name(),
        primaries_colors.join(", "),
        format_abilities(primaries.top_actions()),
    )
    .unwrap();
    out.push_str("};\n\n");

    let all_buyers = ALL_BUYERS;
    out.push_str("export const BUYERS: BuyerData[] = [\n");
    for buyer in &all_buyers {
        let colors: Vec<String> = buyer
            .color_cost()
            .iter()
            .map(|c| format!("'{}'", format_color(c)))
            .collect();
        let materials: Vec<String> = buyer
            .required_materials()
            .iter()
            .map(|m| format!("'{}'", format_material_type(m)))
            .collect();
        write!(
            out,
            "  {{ kind: 'buyer', name: '{}', points: {}, requiredMaterials: [{}], requiredBoats: {}, colorCost: [{}] }},\n",
            buyer.trade().name(),
            buyer.points(),
            materials.join(", "),
            buyer.required_boats(),
            colors.join(", "),
        )
        .unwrap();
    }
    out.push_str("];\n\n");

    // CARD_LOOKUP
    out.push_str("const CARD_LOOKUP: Record<string, AnyCardData> = {};\n\n");

    // Register basic pigments
    for card in starter_pigment_cards() {
        let variant = card_variant_name(&card);
        write!(
            out,
            "CARD_LOOKUP['{}'] = {{ kind: 'starterPigment', name: '{}', color: '{}', topActions: {} }};\n",
            variant,
            card.name(),
            format_color(&card.colors()[0]),
            format_abilities(card.top_actions()),
        )
        .unwrap();
    }
    out.push('\n');

    // Register pigment cards
    for (i, card) in draft_pigment_cards().iter().enumerate() {
        let variant = card_variant_name(card);
        write!(out, "CARD_LOOKUP['{}'] = PIGMENT_CARDS[{}];\n", variant, i).unwrap();
    }
    out.push('\n');

    // Register starter materials
    for (i, card) in starter_material_cards().iter().enumerate() {
        let variant = card_variant_name(card);
        write!(out, "CARD_LOOKUP['{}'] = MATERIAL_CARDS[{}];\n", variant, i).unwrap();
    }
    out.push('\n');

    // Register draft materials
    for (i, card) in draft_material_cards().enumerate() {
        let variant = card_variant_name(&card);
        write!(
            out,
            "CARD_LOOKUP['{}'] = DRAFT_MATERIAL_CARDS[{}];\n",
            variant, i
        )
        .unwrap();
    }
    out.push('\n');

    // Register action cards
    for (i, card) in action_cards().iter().enumerate() {
        let variant = card_variant_name(card);
        write!(out, "CARD_LOOKUP['{}'] = SPECIAL_CARDS[{}];\n", variant, i).unwrap();
    }
    out.push_str("CARD_LOOKUP['Chalk'] = CHALK_CARD;\n");
    out.push_str("CARD_LOOKUP['Primaries'] = PRIMARIES_CARD;\n\n");

    // BUYER_LOOKUP
    out.push_str("const BUYER_LOOKUP: Record<string, BuyerData> = {};\n");
    for (i, buyer) in all_buyers.iter().enumerate() {
        let variant = buyer_variant_name(buyer);
        write!(
            out,
            "BUYER_LOOKUP['{}'] = BUYERS[{}];\n",
            variant, i
        )
        .unwrap();
    }
    out.push('\n');

    // Lookup functions
    out.push_str("export function getCardData(card: Card): AnyCardData {\n  return CARD_LOOKUP[card];\n}\n\n");
    out.push_str("export function getBuyerData(buyer: Buyer): BuyerData {\n  return BUYER_LOOKUP[buyer];\n}\n\n");
    out.push_str("export function getAnyCardData(card: string): AnyCardData {\n  return CARD_LOOKUP[card] ?? BUYER_LOOKUP[card];\n}\n\n");

    // getCardColors
    out.push_str(
        "export function getCardColors(card: string): Color[] {\n\
         \x20 const data = getAnyCardData(card);\n\
         \x20 if (!data) return [];\n\
         \x20 switch (data.kind) {\n\
         \x20   case 'pigment': return data.colors;\n\
         \x20   case 'starterPigment': return [data.color];\n\
         \x20   case 'material': return data.color ? Array(data.colorCount ?? 1).fill(data.color) : [];\n\
         \x20   case 'special': return [];\n\
         \x20   case 'buyer': return [];\n\
         \x20 }\n\
         }\n\n",
    );

    // DRAFT_COPY_COUNTS
    out.push_str("export const DRAFT_COPY_COUNTS: Record<string, number> = {};\n");
    for (card, copies) in draft_deck_cards() {
        write!(
            out,
            "DRAFT_COPY_COUNTS['{}'] = {};\n",
            card.name().replace('\'', "\\'"),
            copies,
        )
        .unwrap();
    }
    out.push('\n');

    // getDraftCopies
    out.push_str("export function getDraftCopies(name: string): number {\n  return DRAFT_COPY_COUNTS[name] ?? 1;\n}\n\n");

    // CardCategory interface
    out.push_str("export interface CardCategory {\n  label: string;\n  cardNames: string[];\n  totalCopies: number;\n}\n\n");

    // DRAFT_CARD_CATEGORIES
    fn format_category(out: &mut String, label: &str, cards: &[Card]) {
        let names_str: String = cards
            .iter()
            .map(|c| format!("'{}'", c.name().replace('\'', "\\'")))
            .collect::<Vec<_>>()
            .join(", ");
        let total_copies: usize = cards.iter().map(|&c| draft_copies(c)).sum();
        write!(
            out,
            "  {{ label: '{}', cardNames: [{}], totalCopies: {} }},\n",
            label, names_str, total_copies,
        )
        .unwrap();
    }

    // A pigment's tier shows in how many colours it carries.
    let pigments_with = |color_count: usize| -> Vec<Card> {
        draft_pigment_cards().into_iter().filter(|c| c.colors().len() == color_count).collect()
    };

    out.push_str("export const DRAFT_CARD_CATEGORIES: CardCategory[] = [\n");
    format_category(&mut out, "Primary Pigments", &pigments_with(3));
    format_category(&mut out, "Secondary Pigments", &pigments_with(2));
    format_category(&mut out, "Tertiary Pigments", &pigments_with(1));
    format_category(&mut out, "Primaries", &[primaries_card()]);
    format_category(&mut out, "Special Cards", &action_cards());
    format_category(&mut out, "Material + Color", &material_color_cards());
    format_category(&mut out, "Dual Materials", &dual_material_cards());
    out.push_str("];\n\n");

    // getStarterCardCategories
    let starter_pigment_names: Vec<String> = starter_pigment_cards()
        .iter()
        .map(|c| format!("'{}'", c.name()))
        .collect();
    let starter_mat_names: Vec<String> = starter_material_cards()
        .iter()
        .map(|c| format!("'{}'", c.name()))
        .collect();

    out.push_str("export function getStarterCardCategories(numPlayers: number): CardCategory[] {\n");
    write!(
        out,
        "  const starterPigmentNames = [{}];\n",
        starter_pigment_names.join(", ")
    )
    .unwrap();
    write!(
        out,
        "  const starterMaterialNames = [{}];\n",
        starter_mat_names.join(", ")
    )
    .unwrap();
    out.push_str("  return [\n");
    out.push_str("    { label: 'Starter Pigments', cardNames: starterPigmentNames, totalCopies: starterPigmentNames.length * numPlayers },\n");
    out.push_str("    { label: 'Starter Materials', cardNames: starterMaterialNames, totalCopies: starterMaterialNames.length * numPlayers },\n");
    out.push_str("    { label: 'Chalk', cardNames: ['Chalk'], totalCopies: 1 * numPlayers },\n");
    out.push_str("  ];\n");
    out.push_str("}\n");

    // Write the file
    let out_path = std::path::Path::new("..").join("src").join("data").join("cards.ts");
    let mut file = std::fs::File::create(&out_path).expect("failed to create cards.ts");
    file.write_all(out.as_bytes())
        .expect("failed to write cards.ts");
}
