use colori_core::cards::*;
use colori_core::colors::SECONDARIES;
use colori_core::types::*;
use std::fmt::Write as FmtWrite;
use std::io::Write;

fn format_ability(ability: &Ability) -> String {
    match ability {
        Ability::Workshop { count } => format!("{{ type: 'workshop', count: {} }}", count),
        Ability::MixColors { count } => format!("{{ type: 'mixColors', count: {} }}", count),
        Ability::MoveToDraftPool => "{ type: 'moveToDraftPool' }".to_string(),
        Ability::Sell => "{ type: 'sell' }".to_string(),
        Ability::GainDucats { count } => format!("{{ type: 'gainDucats', count: {} }}", count),
        Ability::GainSecondary => "{ type: 'gainSecondary' }".to_string(),
        Ability::GainWildPrimaries { count } => format!("{{ type: 'gainWildPrimaries', count: {} }}", count),
        Ability::GainBoats { count } => format!("{{ type: 'gainBoats', count: {} }}", count),
    }
}

fn format_abilities(abilities: &[Ability]) -> String {
    let formatted: Vec<String> = abilities.iter().map(format_ability).collect();
    format!("[{}]", formatted.join(", "))
}

fn format_color(color: &Color) -> &'static str {
    match color {
        Color::Red => "Red",
        Color::Vermilion => "Vermilion",
        Color::Orange => "Orange",
        Color::Amber => "Amber",
        Color::Yellow => "Yellow",
        Color::Chartreuse => "Chartreuse",
        Color::Green => "Green",
        Color::Teal => "Teal",
        Color::Blue => "Blue",
        Color::Ultramarine => "Ultramarine",
        Color::Purple => "Purple",
        Color::Fuchsia => "Fuchsia",
    }
}

fn format_material_type(mt: &MaterialType) -> &'static str {
    match mt {
        MaterialType::Textiles => "Textiles",
        MaterialType::Ceramics => "Ceramics",
        MaterialType::Paintings => "Paintings",
    }
}

fn card_variant_name(card: &Card) -> String {
    serde_json::to_value(card)
        .unwrap()
        .as_str()
        .unwrap()
        .to_string()
}

fn sell_card_variant_name(sell_card: &SellCard) -> String {
    serde_json::to_value(sell_card)
        .unwrap()
        .as_str()
        .unwrap()
        .to_string()
}

fn write_dye_card(out: &mut String, card: &Card) {
    let name = card.name();
    let colors = card.colors();
    let colors_str: Vec<String> = colors.iter().map(|c| format!("'{}'", format_color(c))).collect();
    write!(
        out,
        "  {{\n    kind: 'dye',\n    name: '{}',\n    colors: [{}],\n    trashAbilities: {},\n  }},\n",
        name.replace('\'', "\\'"),
        colors_str.join(", "),
        format_abilities(card.trash_abilities()),
    )
    .unwrap();
}

fn write_basic_dye_card(out: &mut String, card: &Card) {
    let name = card.name();
    let color = card.colors()[0];
    write!(
        out,
        "  {{\n    kind: 'basicDye',\n    name: '{}',\n    color: '{}',\n    trashAbilities: {},\n  }},\n",
        name,
        format_color(&color),
        format_abilities(card.trash_abilities()),
    )
    .unwrap();
}

fn write_material_card(out: &mut String, card: &Card) {
    let name = card.name();
    let material_types = card.material_types();
    let colors = card.colors();

    let mt_str: Vec<String> = material_types
        .iter()
        .map(|mt| format!("'{}'", format_material_type(mt)))
        .collect();

    write!(out, "  {{\n    kind: 'material',\n    name: '{}',\n    materialTypes: [{}],\n", name.replace('\'', "\\'"), mt_str.join(", ")).unwrap();
    if !colors.is_empty() {
        write!(out, "    color: '{}',\n", format_color(&colors[0])).unwrap();
        if colors.len() > 1 {
            write!(out, "    colorCount: {},\n", colors.len()).unwrap();
        }
    }
    write!(out, "    trashAbilities: {},\n  }},\n", format_abilities(card.trash_abilities())).unwrap();
}

fn write_action_card(out: &mut String, card: &Card) {
    let name = card.name();

    write!(
        out,
        "  {{\n    kind: 'action',\n    name: '{}',\n    trashAbilities: {},\n    workshopAbilities: {},\n  }},\n",
        name,
        format_abilities(card.trash_abilities()),
        format_abilities(card.workshop_abilities()),
    )
    .unwrap();
}

fn main() {
    println!("cargo:rerun-if-changed=../colori-core/src/types.rs");
    println!("cargo:rerun-if-changed=../colori-core/src/cards.rs");
    println!("cargo:rerun-if-changed=../colori-core/src/colors.rs");
    println!("cargo:rerun-if-changed=build.rs");

    let mut out = String::new();

    // Header
    out.push_str("// AUTO-GENERATED by colori-wasm/build.rs — do not edit by hand\n");
    out.push_str("import type { Card, SellCard, Color, AnyCardData, DyeCardData, BasicDyeCardData, MaterialCardData, ActionCardData, SellCardData } from './types';\n\n");

    // DYE_CARDS
    out.push_str("export const DYE_CARDS: DyeCardData[] = [\n");
    for card in draft_dye_cards() {
        write_dye_card(&mut out, &card);
    }
    out.push_str("];\n\n");

    // MATERIAL_CARDS (starter materials)
    out.push_str("export const MATERIAL_CARDS: MaterialCardData[] = [\n");
    for card in starter_material_cards() {
        write_material_card(&mut out, &card);
    }
    out.push_str("];\n\n");

    // DRAFT_MATERIAL_CARDS
    out.push_str("export const DRAFT_MATERIAL_CARDS: MaterialCardData[] = [\n");
    for card in draft_material_cards() {
        write_material_card(&mut out, &card);
    }
    out.push_str("];\n\n");

    // BASIC_DYE_CARDS
    out.push_str("export const BASIC_DYE_CARDS: BasicDyeCardData[] = [\n");
    for card in basic_dye_cards() {
        write_basic_dye_card(&mut out, &card);
    }
    out.push_str("];\n\n");

    // ACTION_CARDS
    out.push_str("export const ACTION_CARDS: ActionCardData[] = [\n");
    for card in action_cards() {
        write_action_card(&mut out, &card);
    }
    out.push_str("];\n\n");

    let secondaries: Vec<String> =
        SECONDARIES.iter().map(|c| format!("'{}'", format_color(c))).collect();
    write!(out, "export const SECONDARIES: Color[] = [{}];\n\n", secondaries.join(", ")).unwrap();

    write!(out, "export const STARTER_DECK_SIZE = {};\n\n", starter_deck().len()).unwrap();

    // CHALK_CARD
    let chalk = chalk_card();
    out.push_str("export const CHALK_CARD: ActionCardData = {\n");
    write!(
        out,
        "  kind: 'action',\n  name: '{}',\n  trashAbilities: {},\n  workshopAbilities: {},\n",
        chalk.name(),
        format_abilities(chalk.trash_abilities()),
        format_abilities(chalk.workshop_abilities()),
    )
    .unwrap();
    out.push_str("};\n\n");

    let all_sell_cards = ALL_SELL_CARDS;
    out.push_str("export const SELL_CARDS: SellCardData[] = [\n");
    for sell_card in &all_sell_cards {
        let colors: Vec<String> = sell_card
            .color_cost()
            .iter()
            .map(|c| format!("'{}'", format_color(c)))
            .collect();
        let materials: Vec<String> = sell_card
            .required_materials()
            .iter()
            .map(|m| format!("'{}'", format_material_type(m)))
            .collect();
        write!(
            out,
            "  {{ kind: 'sellCard', name: '{}', points: {}, requiredMaterials: [{}], requiredBoats: {}, colorCost: [{}] }},\n",
            sell_card.buyer().name(),
            sell_card.points(),
            materials.join(", "),
            sell_card.required_boats(),
            colors.join(", "),
        )
        .unwrap();
    }
    out.push_str("];\n\n");

    // CARD_LOOKUP
    out.push_str("const CARD_LOOKUP: Record<string, AnyCardData> = {};\n\n");

    // Register basic dyes
    for card in basic_dye_cards() {
        let variant = card_variant_name(&card);
        write!(
            out,
            "CARD_LOOKUP['{}'] = {{ kind: 'basicDye', name: '{}', color: '{}', trashAbilities: {} }};\n",
            variant,
            card.name(),
            format_color(&card.colors()[0]),
            format_abilities(card.trash_abilities()),
        )
        .unwrap();
    }
    out.push('\n');

    // Register dye cards
    for (i, card) in draft_dye_cards().iter().enumerate() {
        let variant = card_variant_name(card);
        write!(out, "CARD_LOOKUP['{}'] = DYE_CARDS[{}];\n", variant, i).unwrap();
    }
    out.push('\n');

    // Register starter materials
    for (i, card) in starter_material_cards().iter().enumerate() {
        let variant = card_variant_name(card);
        write!(out, "CARD_LOOKUP['{}'] = MATERIAL_CARDS[{}];\n", variant, i).unwrap();
    }
    out.push('\n');

    // Register draft materials
    for (i, card) in draft_material_cards().enumerate() {
        let variant = card_variant_name(&card);
        write!(
            out,
            "CARD_LOOKUP['{}'] = DRAFT_MATERIAL_CARDS[{}];\n",
            variant, i
        )
        .unwrap();
    }
    out.push('\n');

    // Register action cards
    for (i, card) in action_cards().iter().enumerate() {
        let variant = card_variant_name(card);
        write!(out, "CARD_LOOKUP['{}'] = ACTION_CARDS[{}];\n", variant, i).unwrap();
    }
    out.push_str("CARD_LOOKUP['Chalk'] = CHALK_CARD;\n\n");

    // SELL_CARD_LOOKUP
    out.push_str("const SELL_CARD_LOOKUP: Record<string, SellCardData> = {};\n");
    for (i, sell_card) in all_sell_cards.iter().enumerate() {
        let variant = sell_card_variant_name(sell_card);
        write!(
            out,
            "SELL_CARD_LOOKUP['{}'] = SELL_CARDS[{}];\n",
            variant, i
        )
        .unwrap();
    }
    out.push('\n');

    // Lookup functions
    out.push_str("export function getCardData(card: Card): AnyCardData {\n  return CARD_LOOKUP[card];\n}\n\n");
    out.push_str("export function getSellCardData(sellCard: SellCard): SellCardData {\n  return SELL_CARD_LOOKUP[sellCard];\n}\n\n");
    out.push_str("export function getAnyCardData(card: string): AnyCardData {\n  return CARD_LOOKUP[card] ?? SELL_CARD_LOOKUP[card];\n}\n\n");

    // getCardColors
    out.push_str(
        "export function getCardColors(card: string): Color[] {\n\
         \x20 const data = getAnyCardData(card);\n\
         \x20 if (!data) return [];\n\
         \x20 switch (data.kind) {\n\
         \x20   case 'dye': return data.colors;\n\
         \x20   case 'basicDye': return [data.color];\n\
         \x20   case 'material': return data.color ? Array(data.colorCount ?? 1).fill(data.color) : [];\n\
         \x20   case 'action': return [];\n\
         \x20   case 'sellCard': return [];\n\
         \x20 }\n\
         }\n\n",
    );

    // DRAFT_COPY_COUNTS
    out.push_str("export const DRAFT_COPY_COUNTS: Record<string, number> = {};\n");
    for (card, copies) in draft_deck_cards() {
        write!(
            out,
            "DRAFT_COPY_COUNTS['{}'] = {};\n",
            card.name().replace('\'', "\\'"),
            copies,
        )
        .unwrap();
    }
    out.push('\n');

    // getDraftCopies
    out.push_str("export function getDraftCopies(name: string): number {\n  return DRAFT_COPY_COUNTS[name] ?? 1;\n}\n\n");

    // CardCategory interface
    out.push_str("export interface CardCategory {\n  label: string;\n  cardNames: string[];\n  totalCopies: number;\n}\n\n");

    // DRAFT_CARD_CATEGORIES
    fn format_category(out: &mut String, label: &str, cards: &[Card]) {
        let names_str: String = cards
            .iter()
            .map(|c| format!("'{}'", c.name().replace('\'', "\\'")))
            .collect::<Vec<_>>()
            .join(", ");
        let total_copies: usize = cards.iter().map(|&c| draft_copies(c)).sum();
        write!(
            out,
            "  {{ label: '{}', cardNames: [{}], totalCopies: {} }},\n",
            label, names_str, total_copies,
        )
        .unwrap();
    }

    // A dye's tier shows in how many colours it carries.
    let dyes_with = |color_count: usize| -> Vec<Card> {
        draft_dye_cards().into_iter().filter(|c| c.colors().len() == color_count).collect()
    };

    out.push_str("export const DRAFT_CARD_CATEGORIES: CardCategory[] = [\n");
    format_category(&mut out, "Primary Dyes", &dyes_with(3));
    format_category(&mut out, "Secondary Dyes", &dyes_with(2));
    format_category(&mut out, "Tertiary Dyes", &dyes_with(1));
    format_category(&mut out, "Action Cards", &action_cards());
    format_category(&mut out, "Material + Color", &material_color_cards());
    format_category(&mut out, "Dual Materials", &dual_material_cards());
    out.push_str("];\n\n");

    // getStarterCardCategories
    let starter_dye_names: Vec<String> = basic_dye_cards()
        .iter()
        .map(|c| format!("'{}'", c.name()))
        .collect();
    let starter_mat_names: Vec<String> = starter_material_cards()
        .iter()
        .map(|c| format!("'{}'", c.name()))
        .collect();

    out.push_str("export function getStarterCardCategories(numPlayers: number): CardCategory[] {\n");
    write!(
        out,
        "  const starterDyeNames = [{}];\n",
        starter_dye_names.join(", ")
    )
    .unwrap();
    write!(
        out,
        "  const starterMaterialNames = [{}];\n",
        starter_mat_names.join(", ")
    )
    .unwrap();
    out.push_str("  return [\n");
    out.push_str("    { label: 'Starter Dyes', cardNames: starterDyeNames, totalCopies: starterDyeNames.length * numPlayers },\n");
    out.push_str("    { label: 'Starter Materials', cardNames: starterMaterialNames, totalCopies: starterMaterialNames.length * numPlayers },\n");
    out.push_str("    { label: 'Chalk', cardNames: ['Chalk'], totalCopies: 1 * numPlayers },\n");
    out.push_str("  ];\n");
    out.push_str("}\n");

    // Write the file
    let out_path = std::path::Path::new("..").join("src").join("data").join("cards.ts");
    let mut file = std::fs::File::create(&out_path).expect("failed to create cards.ts");
    file.write_all(out.as_bytes())
        .expect("failed to write cards.ts");
}
